CREATE TABLE app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL CHECK (role IN ('USER', 'ADMIN'))
);

CREATE TABLE portfolios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    name VARCHAR(100) NOT NULL,
    base_currency VARCHAR(3) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    version BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX portfolios_owner_idx ON portfolios(user_id, id);

CREATE TABLE ledger_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    portfolio_id BIGINT NOT NULL REFERENCES portfolios(id) ON DELETE CASCADE,
    type VARCHAR(10) NOT NULL CHECK (type IN ('BUY', 'SELL', 'DEPOSIT', 'WITHDRAW')),
    symbol VARCHAR(32),
    qty NUMERIC(20,8),
    price NUMERIC(19,4),
    fee NUMERIC(19,4) NOT NULL DEFAULT 0 CHECK (fee >= 0),
    timestamp TIMESTAMPTZ NOT NULL,
    note VARCHAR(500),
    CHECK (qty IS NULL OR qty > 0),
    CHECK (price IS NULL OR price > 0),
    CHECK (type NOT IN ('BUY', 'SELL') OR (symbol IS NOT NULL AND length(symbol) > 0 AND qty IS NOT NULL AND price IS NOT NULL))
);
CREATE INDEX ledger_portfolio_order_idx ON ledger_transactions(portfolio_id, timestamp, id);

CREATE TABLE idempotency_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    portfolio_id BIGINT NOT NULL REFERENCES portfolios(id) ON DELETE CASCADE,
    idempotency_key VARCHAR(128) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    response_body TEXT NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    UNIQUE(portfolio_id, idempotency_key)
);
CREATE INDEX idempotency_expiry_idx ON idempotency_records(expires_at);

CREATE TABLE goals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    portfolio_id BIGINT NOT NULL REFERENCES portfolios(id) ON DELETE CASCADE,
    name VARCHAR(100) NOT NULL,
    target_amount NUMERIC(19,4) NOT NULL CHECK (target_amount > 0),
    target_date TIMESTAMPTZ NOT NULL,
    current_amount NUMERIC(19,4) NOT NULL DEFAULT 0 CHECK (current_amount >= 0),
    version BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX goals_portfolio_idx ON goals(portfolio_id);

CREATE TABLE plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    portfolio_id BIGINT NOT NULL REFERENCES portfolios(id) ON DELETE CASCADE,
    symbol VARCHAR(32) NOT NULL,
    amount_per_interval NUMERIC(19,4) NOT NULL CHECK (amount_per_interval > 0),
    interval VARCHAR(10) NOT NULL CHECK (interval IN ('WEEKLY', 'MONTHLY')),
    start_date TIMESTAMPTZ NOT NULL,
    end_date TIMESTAMPTZ,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    version BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX plans_portfolio_idx ON plans(portfolio_id);

CREATE TABLE candles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol VARCHAR(32) NOT NULL,
    date DATE NOT NULL,
    open NUMERIC(19,4) NOT NULL,
    high NUMERIC(19,4) NOT NULL,
    low NUMERIC(19,4) NOT NULL,
    close NUMERIC(19,4) NOT NULL,
    volume BIGINT NOT NULL,
    UNIQUE(symbol, date)
);
