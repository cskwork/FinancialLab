#!/usr/bin/env python3
"""Reproduce the checked-in migration from the unmodified frontend CSV samples."""
import csv
from pathlib import Path

root = Path(__file__).resolve().parents[2]
target = root / "backend/src/main/resources/db/migration/V3__seed_sample_market_data.sql"
lines = ["-- Generated by backend/scripts/generate-market-data.py from frontend/public/data/ohlcv/*.csv.",
         "-- Samples are demo data, not a live market feed."]
for source in sorted((root / "frontend/public/data/ohlcv").glob("*.csv")):
    with source.open() as stream:
        for row in csv.DictReader(stream):
            values = ", ".join(row[key] for key in ("open", "high", "low", "close", "volume"))
            lines.append("INSERT INTO candles (symbol, date, open, high, low, close, volume) "
                         f"VALUES ('{source.stem}', '{row['date']}', {values});")
target.write_text("\n".join(lines) + "\n")
